ROWS = [("あ行", "あいうえお"), ("か行", "かきくけこ"), ("さ行", "さしすせそ"), ("た行", "たちつてと"), ("な行", "なにぬねの"),
        ("は行", "はひふへほ"), ("ま行", "まみむめも"), ("や行", "やゆよ"), ("ら行", "らりるれろ"), ("わ行", "わをん")]
OTHER = "その他"
VOWEL = {}
for _v, _chars in zip("あいうえお", ["あかさたなはまやらわ", "いきしちにひみり", "うくすつぬふむゆる", "えけせてねへめれ", "おこそとのほもよろを"]):
    for _c in _chars:
        VOWEL[_c] = _v
KANA = re.compile(r"^[ぁ-ゖァ-ヺー・ 　]+$")


def reading(name):
    if name in READINGS:
        return READINGS[name]
    if KANA.match(name):
        return "".join(chr(ord(c) - 0x60) if "ァ" <= c <= "ヶ" else c for c in name if c not in "・ 　")
    return None


def base_kana(text):
    """濁点・半濁点・小書きを外した読み（並べ替えと行分けに使う）。"""
    t = unicodedata.normalize("NFKD", text)
    t = "".join(c for c in t if c not in "゙゚")
    small = str.maketrans("ぁぃぅぇぉっゃゅょゎ", "あいうえおつやゆよわ")
    t = t.translate(small)
    out = []
    for c in t:
        if c == "ー" and out:
            c = VOWEL.get(out[-1], c)
        out.append(c)
    return "".join(out)


def row_of(name):
    y = reading(name)
    if not y:
        return OTHER
    head = base_kana(y)[0]
    for row, chars in ROWS:
        if head in chars:
            return row
    return OTHER


def sort_key(name):
    y = reading(name)
    return (y is None, base_kana(y) if y else name, y or "", name)
